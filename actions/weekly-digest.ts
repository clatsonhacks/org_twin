import { defineAction } from "@agent-native/core/action";
import { z } from "zod";

import { httpJson } from "../server/connectors/http.js";
import { secret } from "../server/connectors/registry.js";
import { buildDigest } from "../server/org/digest.js";
import { owner } from "./lib/owner.js";

export default defineAction({
  description:
    "Build the weekly digest (hours saved by team, runs, most used skills, approvals waiting, open requests) from the database. post='slack' or 'discord' also posts it to the company's connected channel; the text is generated by OrgTwin, not written by the agent, so it needs no extra approval. The recurring job calls this.",
  schema: z.object({ post: z.enum(["none", "slack", "discord"]).default("none") }),
  run: async ({ post }, ctx) => {
    const digest = await buildDigest(owner(ctx));
    let posted: string | null = null;
    if (post === "slack") {
      const url = await secret("SLACK_WEBHOOK_URL");
      if (url) {
        await httpJson(url, { method: "POST", json: { text: digest.text } }, "Slack");
        posted = "slack";
      }
    } else if (post === "discord") {
      const url = await secret("DISCORD_WEBHOOK_URL");
      if (url) {
        await httpJson(url, { method: "POST", json: { content: digest.text.replace(/\*/g, "**").slice(0, 2000) } }, "Discord");
        posted = "discord";
      }
    }
    return { ...digest, posted, note: post !== "none" && !posted ? `${post} is not connected; digest not posted.` : null };
  },
});
